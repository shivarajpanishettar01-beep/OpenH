"""robot_control: the only node that commands the UR7e.

Runs in the same process as robot_state (shared memory for the latest RTDE sample and for the
mode / safety_flags / action_source / action_is_expert fields of /robot/state).

* Refuses to start while any limit in rig.yaml is null, and says which.
* Every command passes the safety filter (workspace box, tilt cone, speed, acceleration).
* Any hard violation (measured state outside a limit, force above the ceiling, stale state)
  -> stop, mode FAULT; motion resumes only after {"cmd": "ack_fault"} on /operator/command.
* Deadman: in teleop, no /teleop/twist within the timeout -> zero velocity.

Motion is generated by one active Motion object at a time; services start a motion and wait
for it to finish. Test in URSim before the real robot.
"""
