class RobotControlNode(Node):

    def __init__(self, state_node: RobotStateNode, status: ControlStatus, rig: dict, **kw):
        super().__init__('robot_control', **kw)
        self.declare_parameter('session_json', '')
        self.state_node, self.status, self.rig = state_node, status, rig
        self.lim = safety.Limits.from_rig(rig)
        g = lambda k, d=None: config.get_path(rig, k, d)  # noqa: E731
        self.rate = float(g('robot.control_rate_hz') or 125.0)
        self.kp = float(g('motion.position_gain_per_s') or 2.0)
        self.kr = float(g('motion.rotation_gain_per_s') or 2.0)
        self.transit_speed = float(g('motion.transit_speed_mm_s')) / 1000.0
        self.descent_speed = float(g('motion.descent_speed_mm_s')) / 1000.0
        self.descent_travel = float(g('motion.descent_max_travel_mm')) / 1000.0
        self.retract_dist = float(g('motion.retract_distance_mm')) / 1000.0
        self.path_accel = float(g('motion.path_accel_mm_s2') or g('limits.max_linear_accel_mm_s2')) / 1000.0
        self.path_rot_radius = float(g('motion.path_rotation_radius_mm') or 50.0) / 1000.0
        self.force_setpoint = float(g('limits.force_setpoint_default_n'))
        self.stale_state_s = float(g('robot.max_state_age_s') or 0.02)

        # Same controller as robot_state (URSim in the dry run, the UR7e otherwise).
        self.backend = make_backend(rig, log=self.get_logger().info, ip=state_node.robot_ip)
        self.rt_priority = int(g('robot.rt_priority') or 0)
        self.get_logger().info(f'connecting control backend: {self.backend.name}')
        self.backend.connect()

        self.motion = Idle()
        self.motion_lock = threading.Lock()
        self.in_contact = False
        self.hold = False             # set by services (episode flow)
        self.operator_pause = False   # toggled by the operator (P); independent of self.hold
        self.fault_flags = 0
        self.recovering_flags = 0
        self.episode_id = ''
        self._twist = (None, 0)
        self._twist_lock = threading.Lock()
        self.v_prev, self.w_prev = np.zeros(3), np.zeros(3)
        self._low_force_since = None    # contact-loss timer (monotonic s)

        cb = ReentrantCallbackGroup()
        self.pub_cmd = self.create_publisher(TwistStamped, '/robot/cmd_executed', 10)
        # mode / flags / source / expert for robot_state_cpp, which merges them into /robot/state
        self.pub_status = self.create_publisher(ControlStatusMsg, '/robot/control_status', 10)
        self.pub_evt = self.create_publisher(EpisodeEvent, '/episode/events', 50)
        self.create_subscription(TwistStamped, '/teleop/twist', self._on_twist, 10, callback_group=cb)
        self.create_subscription(String, '/operator/command', self._on_command, 50, callback_group=cb)
        self.create_subscription(EpisodeEvent, '/episode/events', self._on_event, 50, callback_group=cb)
        self.create_service(Trigger, '/robot/zero_ft', self._srv_zero_ft, callback_group=cb)
        self.create_service(MoveToPose, '/robot/move_to_pose', self._srv_move, callback_group=cb)
        self.create_service(DescendToContact, '/robot/descend_to_contact', self._srv_descend, callback_group=cb)
        self.create_service(SetBool, '/robot/set_teleop', self._srv_teleop, callback_group=cb)
        self.create_service(InjectPerturbation, '/robot/inject_perturbation', self._srv_perturb, callback_group=cb)
        self.create_service(Trigger, '/robot/retract', self._srv_retract, callback_group=cb)
        self.create_service(RunPath, '/robot/run_path', self._srv_run_path, callback_group=cb)
        self.create_service(Trigger, '/robot/protective_stop', self._srv_pstop, callback_group=cb)

        self._stop = threading.Event()
        self._loop = threading.Thread(target=self._control_loop, name='control_loop', daemon=True)
        self._loop.start()

    # ---------------------------------------------------------------- inputs
    def _on_twist(self, msg):
        t = msg.twist
        with self._twist_lock:
            self._twist = ((t.linear.x, t.linear.y, t.linear.z, t.angular.x, t.angular.y, t.angular.z),
                           now_ns())

    def latest_twist(self):
        with self._twist_lock:
            return self._twist

    def _on_event(self, msg):
        if msg.kind == 'start':
            self.episode_id = msg.episode_id
        elif msg.kind == 'end':
            self.episode_id = ''

    def _on_command(self, msg):
        try:
            c = json.loads(msg.data)
        except ValueError:
            return
        cmd = c.get('cmd')
        if cmd == 'ack_fault':
            self._ack_fault()
        elif cmd == 'force_step':
            lo, hi = self.lim.force_band_n
            self.force_setpoint = float(np.clip(self.force_setpoint + float(c.get('delta', 0.0)), lo, hi))
            self._event('note', {'force_setpoint_n': self.force_setpoint})
        elif cmd == 'recontact':
            threading.Thread(target=self._recontact, daemon=True).start()
        elif cmd == 'hold':
            self.operator_pause = bool(c.get('value', not self.operator_pause))
            self._event('note', {'operator_pause': self.operator_pause})

    # ---------------------------------------------------------------- helpers
    def held(self):
        """Motion paused by the episode flow (hold) or by the operator (P)."""
        return self.hold or self.operator_pause

    def _event(self, kind, value, stamp_ns=None):
        e = EpisodeEvent()
        e.header.stamp = stamp_from_ns(stamp_ns or now_ns())
        e.episode_id = self.episode_id
        e.kind = kind
        e.value = json.dumps(value)
        self.pub_evt.publish(e)

    def _set_motion(self, m):
        with self.motion_lock:
            if self.status.mode == ST.MODE_FAULT:
                m.finish(False, 'robot in FAULT; acknowledge first')
                return m
            old = self.motion
            self.motion = m
        if not old.done.is_set():
            old.finish(False, 'preempted')
        return m

    def _move_timeout(self, T_target, speed):
        """Generous time for a linear move: 3x the nominal time + 5 s. A target that the envelope or
        the tilt cone makes unreachable ends as 'timeout' instead of blocking the service forever."""
        s = self.state_node.get_latest()
        if s is None:
            return 10.0
        dp, dr = geometry.pose_error(geometry.pose_from_ur(s.tcp_pose), T_target)
        t = max(np.linalg.norm(dp) / max(speed, 1e-6), np.linalg.norm(dr) / max(self.lim.w_max, 1e-6))
        return 3.0 * t + 5.0

    def _hold_in_contact_if_idle(self):
        """After a successful descend / path: hold position in force mode, but only if no newer
        motion (e.g. a retract that cancelled it) has taken over in the meantime."""
        with self.motion_lock:
            if not isinstance(self.motion, Idle) or self.status.mode == ST.MODE_FAULT:
                return False
            self.motion = Teleop(self, True)
        self.hold = True
        return True

    def _run(self, m, timeout=None):
        t0 = time.monotonic()
        self._set_motion(m)
        m.done.wait(timeout)
        if not m.done.is_set():
            m.finish(False, 'timeout')
            if self.status.mode != ST.MODE_FAULT:
                try:
                    self.backend.stop()
                except Exception as e:  # noqa: BLE001
                    self.get_logger().error(f'backend stop after timeout failed: {e}')
        # every motion leaves a record: success, timeout, preempted (cancelled), FAULT
        self._event('motion', {'motion': type(m).__name__, 'ok': bool(m.ok), 'message': m.message,
                               'duration_s': round(time.monotonic() - t0, 3)})
        with self.motion_lock:
            if self.motion is m:
                self.motion = Teleop(self, self.in_contact) if isinstance(m, Perturbation) else Idle()
        return m

    def _fault(self, flags, reason):
        with self.motion_lock:
            if self.status.mode == ST.MODE_FAULT:
                return
            self.fault_flags = flags
            with self.status.lock:
                self.status.mode = ST.MODE_FAULT
                self.status.safety_flags |= flags
            m, self.motion = self.motion, Idle()
        try:
            self.backend.stop()
        except Exception as e:  # noqa: BLE001
            self.get_logger().error(f'backend stop failed: {e}')
        m.finish(False, f'FAULT: {reason}')
        self.in_contact = False
        self.get_logger().error(f'FAULT: {reason} {safety.flag_names(flags)}')
        self._event('phase', {'phase': 'fault', 'reason': reason, 'flags': safety.flag_names(flags)})

    def _ack_fault(self):
        s = self.state_node.get_latest()
        if s is None:
            return
        T = geometry.pose_from_ur(s.tcp_pose)
        still = safety.hard_violations(self.lim, T, s.wrench, s.tcp_speed)
        if still & (safety.FLAG_FORCE_MAX | safety.FLAG_SPEED):
            self.get_logger().warn(f'cannot acknowledge: still violated {safety.flag_names(still)}')
            return
        # Outside the box or the tilt cone: acknowledge into recovery. Those two hard checks are
        # suspended until the probe is back inside; the command filter only allows motion that
        # does not go further out.
        self.recovering_flags = still & (safety.FLAG_ENVELOPE | safety.FLAG_TILT_CONE)
        with self.status.lock:
            self.status.mode = ST.MODE_IDLE
            self.status.safety_flags = 0
        self.fault_flags = 0
        self.get_logger().info('fault acknowledged')
        self._event('phase', {'phase': 'fault_ack'})

    def _check_contact(self, m, T, wrench, stamp_ns):
        """D8: in force regulation, a probe-axis force below contact_lost_threshold_n for
        contact_lost_time_s means contact is lost. Stop force mode, hold position, report it."""
        if not (m.force_on and self.in_contact):
            self._low_force_since = None
            return False
        if abs(safety.probe_axis_force(T, wrench)) >= self.lim.contact_lost_n:
            self._low_force_since = None
            return False
        now = time.monotonic()
        if self._low_force_since is None:
            self._low_force_since = now
            return False
        if now - self._low_force_since < self.lim.contact_lost_s:
            return False
        self._low_force_since = None
        self.in_contact = False
        with self.motion_lock:
            old, self.motion = self.motion, Idle()     # Idle: no command, force mode stopped
        try:
            self.backend.stop()
        except Exception as e:  # noqa: BLE001
            self.get_logger().error(f'backend stop on contact loss failed: {e}')
        if not old.done.is_set():
            old.finish(False, 'contact lost')
        self.get_logger().warn('contact lost: force mode stopped, holding position (recontact to resume)')
        self._event('phase', {'phase': 'contact_lost', 'force_axis_n': float(safety.probe_axis_force(T, wrench)),
                              'motion': type(old).__name__}, stamp_ns)
        return True

    def _recontact(self):
        """Operator command after a contact loss: bounded slow descent, then hold in contact."""
        if self.in_contact or self.status.mode == ST.MODE_FAULT:
            return
        self._event('phase', {'phase': 'recontact'})
        self._srv_descend(DescendToContact.Request(), DescendToContact.Response())

    def _phantom_T(self):
        sj = self.get_parameter('session_json').value
        reg = read_json(sj).get('phantom_registration', {}) if sj else {}
        if 'T_base_phantom' not in reg:
            raise RuntimeError('no phantom registration in session.json')
        return np.array(reg['T_base_phantom'])

    # ---------------------------------------------------------------- control loop
    def _control_loop(self):
        from usrig_common.config import set_thread_rt_priority
        ok, msg = set_thread_rt_priority(self.rt_priority)
        (self.get_logger().info if ok else self.get_logger().warn)(f'control loop: {msg}')
        period = 1.0 / self.rate
        nxt = time.monotonic()
        while not self._stop.is_set():
            nxt += period
            try:
                self._tick(period)
            except Exception as e:  # noqa: BLE001
                self._fault(0, f'control loop error: {e}')
            delay = nxt - time.monotonic()
            if delay > 0:
                time.sleep(delay)
            else:
                nxt = time.monotonic()

    def _tick(self, dt):
        # Controller-side deadman: kicked every tick while this loop is alive, whatever the mode.
        self.backend.kick()
        s = self.state_node.get_latest()
        if s is None or (now_ns() - s.stamp_ns) * 1e-9 > self.stale_state_s:
            if self.status.mode not in (ST.MODE_IDLE, ST.MODE_FAULT):
                self._fault(0, 'robot state stale')
            return
        T = geometry.pose_from_ur(s.tcp_pose)
        hard = safety.hard_violations(self.lim, T, s.wrench, s.tcp_speed)
        if self.recovering_flags:
            self.recovering_flags &= hard
            hard &= ~self.recovering_flags
        if hard and self.status.mode != ST.MODE_FAULT:
            self._fault(hard, 'limit violated')
        if self.status.mode == ST.MODE_FAULT:
            self.v_prev, self.w_prev = np.zeros(3), np.zeros(3)
            self._publish_status(s.stamp_ns)
            return

        with self.motion_lock:
            m = self.motion
        if self._check_contact(m, T, s.wrench, s.stamp_ns):
            self.v_prev, self.w_prev = np.zeros(3), np.zeros(3)
            self._publish_status(s.stamp_ns)
            return
        ctx = {'T': T, 'wrench': s.wrench, 'tcp_speed': s.tcp_speed, 'dt': dt,
               'stamp_ns': s.stamp_ns, 'flags': 0}
        v, w = m.step(ctx)
        v, w, lim_flags = safety.filter_command(self.lim, T, v, w, self.v_prev, self.w_prev, dt)
        flags = ctx['flags'] | lim_flags
        self.v_prev, self.w_prev = v, w

        if isinstance(m, Idle) and not np.any(v) and not np.any(w):
            pass  # nothing to send: the robot is not being commanded
        else:
            self.backend.command(T, v, w, self.lim.a_max, m.force_on, self.force_setpoint, dt)

        with self.status.lock:
            self.status.mode = m.mode
            self.status.safety_flags = flags
            self.status.action_source = m.source
            self.status.action_is_expert = bool(m.expert)
            self.status.force_setpoint_n = self.force_setpoint if m.force_on else 0.0

        self._publish_status(s.stamp_ns)
        msg = TwistStamped()
        msg.header.stamp = stamp_from_ns(s.stamp_ns)
        msg.header.frame_id = 'probe'
        vp, wp = geometry.twist_base_to_probe(T, v, w)
        (msg.twist.linear.x, msg.twist.linear.y, msg.twist.linear.z) = map(float, vp)
        (msg.twist.angular.x, msg.twist.angular.y, msg.twist.angular.z) = map(float, wp)
        self.pub_cmd.publish(msg)

    def _publish_status(self, stamp_ns=None):
        fsp, mode, flags, src, expert = self.status.snapshot()
        m = ControlStatusMsg()
        m.header.stamp = stamp_from_ns(stamp_ns or now_ns())
        m.force_setpoint_n = float(fsp)
        m.mode, m.safety_flags, m.action_source, m.action_is_expert = mode, flags, src, bool(expert)
        self.pub_status.publish(m)

    # ---------------------------------------------------------------- services
    def _srv_zero_ft(self, req, res):
        if not isinstance(self.motion, Idle) or self.in_contact:
            res.success, res.message = False, 'zero_ft only when idle and in free air'
            return res
        try:
            self.backend.zero_ft()
            res.success, res.message = True, 'F/T zeroed'
            self._event('phase', {'phase': 'zero_ft'})
        except Exception as e:  # noqa: BLE001
            res.success, res.message = False, str(e)
        return res

    def transit_via_points(self, T_now, T_target, T_base_phantom, safe_h):
        """D11: base-frame poses up (to safe_h in the phantom frame, current orientation), across
        (at safe_h, target orientation), then down to the target. Steps already above safe_h are skipped."""
        inv = geometry.inv(T_base_phantom)
        P_now, P_tgt = inv @ T_now, inv @ T_target
        out = []
        if P_now[2, 3] < safe_h - 1e-4:
            up = P_now.copy()
            up[2, 3] = safe_h
            out.append(T_base_phantom @ up)
        if P_tgt[2, 3] < safe_h - 1e-4:
            across = P_tgt.copy()
            across[2, 3] = safe_h
            out.append(T_base_phantom @ across)
        out.append(T_target)
        return out

    def _srv_move(self, req, res):
        try:
            T = geometry.pose_from_msg(req.target.pose)
            legs = [T]
            if req.target.header.frame_id == 'phantom':
                T_bp = self._phantom_T()
                safe_mm = config.get_path(self.rig, 'motion.transit_safe_height_mm')
                if safe_mm is None:
                    raise RuntimeError('motion.transit_safe_height_mm is null: phantom-frame moves go via a safe '
                                       'height (D11); set it in rig.yaml')
                T = T_bp @ T
                s = self.state_node.get_latest()
                if s is None:
                    raise RuntimeError('no robot state')
                legs = self.transit_via_points(geometry.pose_from_ur(s.tcp_pose), T, T_bp, float(safe_mm) / 1000.0)
        except RuntimeError as e:
            res.success, res.message = False, str(e)
            return res
        speed = req.speed_mm_s / 1000.0 if req.speed_mm_s > 0 else self.transit_speed
        speed = min(speed, self.lim.v_max)
        self.in_contact = False
        self._event('phase', {'phase': 'approach', 'legs': len(legs)})
        for leg in legs:
            m = self._run(LinearMove(self, leg, speed), timeout=self._move_timeout(leg, speed))
            if not m.ok:
                break
        res.success, res.message = m.ok, m.message
        return res

    def _srv_descend(self, req, res):
        if req.force_setpoint_n > 0:
            lo, hi = self.lim.force_band_n
            self.force_setpoint = float(np.clip(req.force_setpoint_n, lo, hi))
        travel = req.max_travel_mm / 1000.0 if req.max_travel_mm > 0 else self.descent_travel
        dspeed = min(self.descent_speed, self.lim.v_max)
        m = self._run(Descent(self, dspeed, travel), timeout=3.0 * travel / dspeed + 5.0)
        res.success, res.message = m.ok, m.message
        res.contact_stamp_s = m.contact_stamp_s
        if m.ok:
            self.in_contact = True
            self._event('phase', {'phase': 'contact', 'force_setpoint_n': self.force_setpoint},
                        int(m.contact_stamp_s * 1e9))
            self._hold_in_contact_if_idle()     # holding still until set_teleop(true)
        return res

    def _srv_teleop(self, req, res):
        if req.data:
            self.hold = False
            m = self._set_motion(Teleop(self, self.in_contact))
            res.success = not m.done.is_set()
            res.message = m.message or 'teleop on'
        else:
            self.hold = True
            res.success, res.message = True, 'teleop holding'
        return res

    def _srv_perturb(self, req, res):
        if req.kind not in ('translate', 'rotate', 'lift') or req.duration_s <= 0:
            res.success, res.message = False, 'kind must be translate|rotate|lift, duration > 0'
            return res
        onset = now_ns()
        res.onset_ns = onset
        self._event('perturbation', {'kind': req.kind, 'delta': list(req.delta),
                                     'duration_s': req.duration_s, 'onset_ns': onset}, onset)
        m = self._run(Perturbation(self, req.kind, req.delta, req.duration_s, self.force_setpoint),
                      timeout=req.duration_s + 5.0)
        res.success, res.message = m.ok, m.message
        return res

    def _srv_retract(self, req, res):
        s = self.state_node.get_latest()
        if s is None:
            res.success, res.message = False, 'no robot state'
            return res
        T = geometry.pose_from_ur(s.tcp_pose)
        T_up = T.copy()
        T_up[:3, 3] = T[:3, 3] - T[:3, 2] * self.retract_dist
        self.in_contact = False
        self.hold = False
        self._event('phase', {'phase': 'retract'})
        m = self._run(LinearMove(self, T_up, self.transit_speed, mode=ST.MODE_RETRACT),
                      timeout=self._move_timeout(T_up, self.transit_speed))
        res.success, res.message = m.ok, m.message
        return res

    def _srv_run_path(self, req, res):
        if not self.in_contact:
            res.success, res.message = False, 'run_path needs contact (descend_to_contact first)'
            return res
        try:
            T_bp = self._phantom_T()
            poses = [T_bp @ geometry.pose_from_msg(p) for p in req.waypoints]
            speed = req.speed_mm_s / 1000.0
            if speed <= 0 or speed > self.lim.v_max:
                raise ValueError(f'speed must be in (0, {self.lim.v_max * 1000:.1f}] mm/s')
            path = geometry.ConstantSpeedPath(poses, speed, min(self.path_accel, self.lim.a_max),
                                             self.path_rot_radius)
        except (RuntimeError, ValueError) as e:
            res.success, res.message = False, str(e)
            return res
        self.hold = False
        self._event('phase', {'phase': 'search', 'path_length_m': path.length, 'speed_mm_s': req.speed_mm_s})
        m = self._run(PathFollow(self, path), timeout=path.duration * 3 + 10.0)
        err = np.asarray(m.errors) if m.errors else np.array([np.nan])
        res.success, res.message = m.ok, m.message
        res.speed_error_mean_pct = float(np.nanmean(err))
        res.speed_error_max_pct = float(np.nanmax(err))
        self._event('note', {'speed_tracking': {'mean_pct': res.speed_error_mean_pct,
                                                'max_pct': res.speed_error_max_pct}})
        if m.ok:
            self._hold_in_contact_if_idle()
        return res

    def _srv_pstop(self, req, res):
        try:
            self.backend.protective_stop()
            res.success, res.message = True, 'protective stop triggered'
        except Exception as e:  # noqa: BLE001
            res.success, res.message = False, str(e)
        self._fault(0, 'protective stop requested')
        return res

    def destroy_node(self):
        self._stop.set()
        self._loop.join(timeout=1.0)
        try:
            self.backend.stop()
        finally:
            self.backend.close()
        super().destroy_node()


def design_requirements(rig):
    """Problems with the rig configuration that make the teleop design unsafe (list of strings).

    D4: rock / tilt / rotate pivot about the active TCP, so the TCP must be the probe face;
    with the flange as TCP, rotations would slide the probe across the phantom.
    """
    problems = []
    if config.get_path(rig, 'probe.tcp_already_includes_probe') is not True:
        problems.append('probe.tcp_already_includes_probe must be true: set the controller TCP to the probe '
                        'face (rotations pivot about the TCP; with the flange they slide the probe)')
    return problems


def remote_control_enabled(ip, timeout=3.0):
    """Ask the dashboard server (read-only query). Returns True / False, or None if unreachable."""
    import socket
    try:
        with socket.create_connection((ip, 29999), timeout=timeout) as s:
            s.recv(1024)
            s.sendall(b'is in remote control\n')
            reply = s.recv(1024).decode().strip().lower()
        return reply.startswith('true')
    except OSError:
        return None


def main(args=None):
    rclpy.init(args=args)
    # Load and check limits before connecting to anything.
    probe = rclpy.create_node('robot_control_cfg')
    probe.declare_parameter('config_dir', '')
    probe.declare_parameter('robot_ip', '')
    cfg_dir = probe.get_parameter('config_dir').value or None
    ip_override = probe.get_parameter('robot_ip').value
    probe.destroy_node()
    rig = config.load_config('rig', cfg_dir)

    def refuse(msg):
        print(f'[robot_control] {msg}', file=sys.stderr)
        rclpy.shutdown()
        sys.exit(2)

    # With robot_ip given (sim:=true -> URSim), the real robot.ip is not needed.
    keys = [k for k in config.MOTION_LIMITS if not (ip_override and k == 'robot.ip')]
    try:
        config.require_limits(rig, keys)
    except config.UnsetLimitError as e:
        refuse(str(e))
    for problem in design_requirements(rig):
        refuse(problem)
    if config.get_path(rig, 'robot.control_backend') != 'rtde':
        refuse('robot.control_backend must be rtde (path B, decided at P3)')
    ip = ip_override or config.get_path(rig, 'robot.ip')
    rc_on = remote_control_enabled(ip)
    if rc_on is None:
        refuse(f'dashboard server {ip}:29999 not reachable; cannot confirm Remote Control')
    if not rc_on:
        refuse(f'{ip} is not in Remote Control: switch it on the pendant (ur_rtde must upload its control script)')

    status = ControlStatus()
    state = control = None
    rc = 0
    try:
        # Embedded reader for control only (latest sample); the recorded /robot/state comes from
        # robot_state_cpp. Without the C++ node (ur_client_library missing) it also publishes.
        publish = not bool(int(__import__('os').environ.get('USRIG_STATE_FROM_CPP', '1')))
        state = RobotStateNode(control_status=status, node_name='robot_control_state', publish_topics=publish)
        control = RobotControlNode(state, status, rig)
        ex = MultiThreadedExecutor(num_threads=6)
        ex.add_node(state)
        ex.add_node(control)
        ex.spin()
    except (RuntimeError, ValueError) as e:
        print(f'[robot_control] {e}', file=sys.stderr)
        rc = 2
    except (KeyboardInterrupt, ExternalShutdownException):
        pass
    finally:
        for n in (control, state):
            if n is not None:
                n.destroy_node()
        if rclpy.ok():
            rclpy.shutdown()
    sys.exit(rc)


if __name__ == '__main__':
    main()
