class Motion:
    mode = ST.MODE_IDLE
    source = ST.SOURCE_NONE
    expert = False
    force_on = False

    def __init__(self):
        self.done = threading.Event()
        self.ok = False
        self.message = ''
        self.t0 = None

    def finish(self, ok, message=''):
        self.ok, self.message = ok, message
        self.done.set()

    def step(self, ctx):
        """Return (v_base, w_base). Call finish() when complete."""
        return np.zeros(3), np.zeros(3)


class Idle(Motion):
    pass


class Teleop(Motion):
    mode = ST.MODE_TELEOP
    source = ST.SOURCE_TELEOP
    expert = True

    def __init__(self, ctl, in_contact):
        super().__init__()
        self.ctl = ctl
        self.force_on = in_contact

    def step(self, ctx):
        tw, t_ns = self.ctl.latest_twist()
        if tw is None or (now_ns() - t_ns) * 1e-9 > self.ctl.lim.deadman_s:
            ctx['flags'] |= safety.FLAG_DEADMAN
            return np.zeros(3), np.zeros(3)
        if self.ctl.hold:
            return np.zeros(3), np.zeros(3)
        v_p, w_p = np.array(tw[:3]), np.array(tw[3:])
        if self.force_on:
            v_p[2] = 0.0      # probe axis is force-regulated; the operator nudges the setpoint
        return geometry.twist_probe_to_base(ctx['T'], v_p, w_p)


class LinearMove(Motion):
    mode = ST.MODE_MOVING
    source = ST.SOURCE_TRANSIT

    def __init__(self, ctl, T_target, speed, mode=None, tol_m=0.0005, tol_rad=np.radians(0.5)):
        super().__init__()
        self.ctl, self.T_target, self.speed = ctl, T_target, speed
        self.tol_m, self.tol_rad = tol_m, tol_rad
        if mode is not None:
            self.mode = mode

    def step(self, ctx):
        dp, dr = geometry.pose_error(ctx['T'], self.T_target)
        if np.linalg.norm(dp) < self.tol_m and np.linalg.norm(dr) < self.tol_rad:
            self.finish(True, 'reached')
            return np.zeros(3), np.zeros(3)
        v = safety._clamp_norm(self.ctl.kp * dp, self.speed)
        w = safety._clamp_norm(self.ctl.kr * dr, self.ctl.lim.w_max)
        return v, w


class Descent(Motion):
    mode = ST.MODE_DESCENT
    source = ST.SOURCE_TRANSIT

    def __init__(self, ctl, speed, max_travel_m):
        super().__init__()
        self.ctl, self.speed, self.max_travel = ctl, speed, max_travel_m
        self.p0 = None
        self.contact_stamp_s = 0.0

    def step(self, ctx):
        T = ctx['T']
        if self.p0 is None:
            self.p0 = T[:3, 3].copy()
        f_axis = safety.probe_axis_force(T, ctx['wrench'])
        if abs(f_axis) >= self.ctl.lim.contact_threshold_n:
            self.contact_stamp_s = ctx['stamp_ns'] * 1e-9
            self.finish(True, f'contact at {f_axis:.2f} N')
            return np.zeros(3), np.zeros(3)
        if np.linalg.norm(T[:3, 3] - self.p0) > self.max_travel:
            self.finish(False, 'no contact within max travel')
            return np.zeros(3), np.zeros(3)
        return T[:3, 2] * self.speed, np.zeros(3)


class PathFollow(Motion):
    mode = ST.MODE_MOVING
    source = ST.SOURCE_SCRIPTED_TASK
    expert = True
    force_on = True

    def __init__(self, ctl, path: geometry.ConstantSpeedPath):
        super().__init__()
        self.ctl, self.path = ctl, path
        self.t = 0.0
        self.errors = []

    def step(self, ctx):
        if not self.ctl.hold:
            self.t += ctx['dt']
        T_des, sd, done = self.path.sample(self.t)
        T = ctx['T']
        if done:
            self.finish(True, 'path complete')
            return np.zeros(3), np.zeros(3)
        s, _ = self.path.s_of_t(self.t)
        t_lin, t_ang = self.path.tangent_at_s(s)
        sd = 0.0 if self.ctl.hold else sd
        dp, dr = geometry.pose_error(T, T_des)
        v = t_lin * sd + self.ctl.kp * dp
        w = t_ang * sd + self.ctl.kr * dr
        z = T[:3, 2]
        v = v - z * (v @ z)            # probe axis is force-regulated
        # speed tracking over the constant-speed part: measured motion projected on the path
        # tangent, in the same combined metric as the path length.
        if self.path.t_acc <= self.t <= self.path.t_acc + self.path.t_cruise and not self.ctl.hold:
            sp = np.asarray(ctx['tcp_speed'], float)
            r = self.path.r
            v_meas = float(sp[:3] @ t_lin + (r * sp[3:6]) @ (r * t_ang))
            self.errors.append(abs(v_meas - self.path.v) / self.path.v * 100.0)
        return v, w


class Perturbation(Motion):
    mode = ST.MODE_PERTURB
    source = ST.SOURCE_PERTURBATION
    expert = False
    force_on = True

    def __init__(self, ctl, kind, delta, duration, base_fsp):
        super().__init__()
        self.ctl, self.kind, self.delta, self.duration = ctl, kind, np.asarray(delta, float), duration
        self.base_fsp = base_fsp
        self.t = 0.0

    def step(self, ctx):
        self.t += ctx['dt']
        if self.t >= self.duration:
            if self.kind == 'lift':
                self.ctl.force_setpoint = self.base_fsp
            self.finish(True, 'perturbation complete')
            return np.zeros(3), np.zeros(3)
        rate = self.delta / self.duration
        if self.kind == 'translate':
            return geometry.twist_probe_to_base(ctx['T'], rate, np.zeros(3))
        if self.kind == 'rotate':
            return geometry.twist_probe_to_base(ctx['T'], np.zeros(3), rate)
        if self.kind == 'lift':
            self.ctl.force_setpoint = self.base_fsp + float(self.delta[0])
        return np.zeros(3), np.zeros(3)


